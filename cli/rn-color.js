#!/usr/bin/env node
/**
 * Minimal CLI: scaffold a theme file from a brand color.
 *
 * Usage:
 *   npx rn-color init --brand #7C3AED
 *   npx rn-color init --brand #7C3AED --out ./theme.ts --preset vibrant
 */

const fs = require("fs");
const path = require("path");

function parseArgs(argv) {
  const args = { cmd: argv[2], brand: "#7C3AED", out: "theme.ts", preset: null, nightShift: false };
  for (let i = 3; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--brand") args.brand = argv[++i];
    else if (a === "--out") args.out = argv[++i];
    else if (a === "--preset") args.preset = argv[++i];
    else if (a === "--night-shift") args.nightShift = true;
    else if (a === "--help" || a === "-h") args.help = true;
  }
  return args;
}

function scaffold({ brand, out, preset, nightShift }) {
  const presetId =
    preset && /^[a-zA-Z][a-zA-Z0-9]*$/.test(preset) ? preset : null;

  const themeExpr = presetId
    ? `themePresets.${presetId}`
    : `createAppTheme({
  brand: ${JSON.stringify(brand)},
  nightShift: ${nightShift},
  fonts: {
    family: { sans: "System" },
  },
})`;

  const content = `/**
 * Generated by rn-color CLI — react-native-color-library
 * Brand: ${brand}
 */
import {
  ThemeProvider,
  ThemeToggle,
  createAppTheme,
  themePresets,
  useTheme,
  useThemedStyles,
  ThemedView,
  ThemedText,
  ThemedStatusBar,
} from "react-native-color-library";

export const appTheme = ${themeExpr};

export {
  ThemeProvider,
  ThemeToggle,
  useTheme,
  useThemedStyles,
  ThemedView,
  ThemedText,
  ThemedStatusBar,
  appTheme as default,
};

/* Example root:
 *
 * import appTheme, { ThemeProvider, ThemeToggle, ThemedView, ThemedText } from "./theme";
 *
 * export default function App() {
 *   return (
 *     <ThemeProvider theme={appTheme} defaultMode="system">
 *       <ThemedView style={{ flex: 1, padding: 24 }}>
 *         <ThemedStatusBar />
 *         <ThemedText size="xl" weight="bold">Hello</ThemedText>
 *         <ThemeToggle />
 *       </ThemedView>
 *     </ThemeProvider>
 *   );
 * }
 */
`;

  const target = path.resolve(process.cwd(), out);
  fs.writeFileSync(target, content, "utf8");
  console.log(`✔ Wrote ${target}`);
  console.log(`  Wrap your app with <ThemeProvider theme={appTheme}> and drop in <ThemeToggle />.`);
}

function main() {
  const args = parseArgs(process.argv);
  if (!args.cmd || args.cmd === "help" || args.help) {
    console.log(`react-native-color-library CLI

Commands:
  init --brand #HEX [--out theme.ts] [--preset vibrant|minimal|oled|…] [--night-shift]

Examples:
  npx rn-color init --brand #7C3AED
  npx rn-color init --brand #0d9488 --preset soft --out src/theme.ts
`);
    process.exit(args.cmd ? 0 : 1);
  }

  if (args.cmd === "init") {
    scaffold(args);
    return;
  }

  console.error(`Unknown command: ${args.cmd}`);
  process.exit(1);
}

main();
